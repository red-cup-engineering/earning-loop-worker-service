#!/usr/bin/env node
// Deploy the earning-loops Worker through the Cloudflare API: compile the
// Operations record and Group payer list, bundle the selected supplier graph, bind the two R2 buckets,
// set the crons and enable the workers.dev route.
//   CLOUDFLARE_ACCOUNT_ID=… CLOUDFLARE_API_TOKEN=… node scripts/deploy.mjs --operation <operation.json> --group-payers <addresses.json> [--dry-run]
// The token needs Workers Scripts edit on the account. Secrets already set on the Worker are kept.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { projectOperation, deploymentMetadata } from '../src/deployment.mjs';
import { buildWorker } from './build-worker.mjs';
import { commercialOffers, bidAcquisitionProblem } from '../src/opentask-bid-acquisition.mjs';
import { qualifiedInstance } from '../src/opentask-commercial-pass.mjs';
import { researchProductProblem } from '../src/ln-church-research.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : null; };
const operationPath = arg("operation"), payersPath = arg("group-payers"), productsPath = arg("products");
const researchProductsPath = arg('research-products');
if (!operationPath || !payersPath) { console.error("--operation and --group-payers are required"); process.exit(2); }

const record = JSON.parse(readFileSync(operationPath, "utf8"));
const operation = projectOperation(record, { excludeIssuerResearch: process.argv.includes('--exclude-issuer-research') });
const payers = JSON.parse(readFileSync(payersPath, "utf8"));
if (operation.commercial?.enabled && !productsPath) throw new TypeError('--products must select the Public product map for a commercial operation');
const suppliedProducts = productsPath ? JSON.parse(readFileSync(productsPath, 'utf8')) : {};
if (!suppliedProducts || typeof suppliedProducts !== 'object' || Array.isArray(suppliedProducts)) throw new TypeError('Public products must be a productId map');
const productFields = ['name', 'artifactUrl', 'artifactSha256', 'sourceCommit', 'sourceUrl', 'runtime', 'verificationInstructions', 'criteriaEvidence', 'maximumInputBytes', 'agreement'];
const products = Object.fromEntries(Object.entries(suppliedProducts).map(([id, value]) => [id,
  Object.fromEntries(productFields.filter(key => Object.hasOwn(value, key)).map(key => [key, value[key]]))]));
if (operation.commercial?.enabled) for (const offer of commercialOffers(operation.commercial)) {
  if (qualifiedInstance({ ...offer, bidId: offer.bidId ?? '_pending' }, products[offer.productId], operation.merchantPayTo) ||
      !offer.bidId && bidAcquisitionProblem(offer)) throw new TypeError('commercial offer lacks a qualified product or acquisition contract');
}
writeFileSync(join(root, "data/operation.mjs"), `// Generated by scripts/deploy.mjs from the Operations record it is given (--operation). Do not hand-edit.\n// Source: ${record.id}.\nexport default ${JSON.stringify(operation, null, 2)};\n`);
writeFileSync(join(root, "data/group-payers.mjs"), `// Generated by scripts/deploy.mjs from the 561 Group's payer record (observed ${payers["observed-on"]}). Do not hand-edit.\nexport default ${JSON.stringify(payers.addresses.map((a) => a.address.toLowerCase()).sort(), null, 2)};\n`);
writeFileSync(join(root, 'data/products.mjs'), `// Generated from the selected Public product map (--products). No account or contract state.\nexport default ${JSON.stringify(products, null, 2)};\n`);

if (operation.researchProcurement?.enabled && !researchProductsPath) throw new TypeError('--research-products must select Public frozen research products');
const researchSource = researchProductsPath ? JSON.parse(readFileSync(researchProductsPath,'utf8')) : {};
if (!researchSource || typeof researchSource !== 'object' || Array.isArray(researchSource)) throw new TypeError('Public research products must be a productId map');
const researchFields = ['taskId','taskType','taskDefinitionVersion','taskDefinitionDigest','termsDigest','questionSha256','selectedCandidateId','answerReason','reward'];
const researchProducts = Object.fromEntries(Object.entries(researchSource).map(([id,value]) => [id,
  Object.fromEntries(researchFields.filter(key => Object.hasOwn(value,key)).map(key => [key,value[key]]))]));
if (operation.researchProcurement?.enabled && researchProductProblem(operation.researchProcurement,researchProducts[operation.researchProcurement.productId],operation.merchantPayTo))
  throw new TypeError('research instance does not select a qualified frozen Public product');
writeFileSync(join(root,'data/research-products.mjs'), `// Generated from the selected Public research product map. No capabilities or private state.\nexport default ${JSON.stringify(researchProducts,null,2)};\n`);

const built = await buildWorker({ esbuildRoot: arg('esbuild') });
console.log(`${operation.worker}: ${built.record.artifact.bytes} bundled bytes, composition ${built.record.compositionSha256}, crons ${Object.values(operation.crons).join(" | ")}`);
if (process.argv.includes("--dry-run")) process.exit(0);

const account = process.env.CLOUDFLARE_ACCOUNT_ID, token = process.env.CLOUDFLARE_API_TOKEN;
if (!account || !token) { console.error("CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN are required"); process.exit(2); }
const api = `https://api.cloudflare.com/client/v4/accounts/${account}/workers/scripts/${operation.worker}`;
const call = async (url, init) => {
  const response = await fetch(url, { ...init, headers: { authorization: `Bearer ${token}`, ...init.headers } });
  const body = await response.json();
  if (!body.success) throw new Error(`${init.method} ${url.replace(account, "<account>")}: ${JSON.stringify(body.errors)}`);
  return body.result;
};

const form = new FormData();
// Read actual installed settings before promotion, preserving unknown bindings
// and compatibility flags rather than replacing them with a static whitelist.
const existing = await call(`${api}/settings`, { method: 'GET' });
if (operation.issuerResearch && existing.bindings?.some(b => b.name === 'ONCHAIN_SCAN_URL' && b.text))
  throw new TypeError('issuer operation has no subrequest allocation for the installed onchain hook');
const metadata = deploymentMetadata(operation, existing);
form.append("metadata", new Blob([JSON.stringify(metadata)], { type: "application/json" }));
form.append('worker.mjs', new Blob([readFileSync(join(built.directory, 'worker.mjs'))], { type: 'application/javascript+module' }), 'worker.mjs');
let uploaded;
try { uploaded = await call(api, { method: "PUT", body: form }); }
catch (error) {
  // A Durable Object migration is applied once; a redeploy must not repeat it.
  if (!metadata.migrations || !/migration/i.test(error.message)) throw error;
  delete metadata.migrations;
  form.set("metadata", new Blob([JSON.stringify(metadata)], { type: "application/json" }));
  uploaded = await call(api, { method: "PUT", body: form });
}
await call(`${api}/subdomain`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ enabled: true }) });
const crons = operation.clock === "durable-object-alarm" ? [] : Object.values(operation.crons).map((cron) => ({ cron }));
await call(`${api}/schedules`, { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify(crons) });
console.log(`deployed ${operation.worker} (etag ${uploaded.etag?.slice(0, 12) ?? "?"}), clock: ${operation.clock}`);
if (operation.clock === "durable-object-alarm") {
  const subdomain = await call(`https://api.cloudflare.com/client/v4/accounts/${account}/workers/subdomain`, { method: "GET" });
  const armed = await (await fetch(`https://${operation.worker}.${subdomain.subdomain}.workers.dev/clock`)).text();
  console.log(`clock armed: ${armed}`);
}
